{#
  PII 脱敏宏。

  脱敏发生在 OWD 层（明细层）而不是报送层，理由：
    报送层是聚合口径，本来就不含客户标识；真正需要保护的是明细层的客户号与账号。
    明细层一旦落成明文，后面再怎么遮都只是遮展示，数据本身已经泄漏。

  为什么脱敏之后还能做关联分析：
    同一个输入永远得到同一个输出（确定性哈希），所以按客户的聚合、跨表的关联都成立；
    但输出不可逆，反推不出原值。
    列名与账号分别加盐，避免「用一列的结果去猜另一列」。

  盐从环境变量取，不给默认值 —— 缺盐时必须直接失败，
  不然会用空盐静默产出一份「看着像脱敏了、实际可穷举」的数据。
#}
